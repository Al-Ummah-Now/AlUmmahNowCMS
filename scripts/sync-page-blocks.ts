/**
 * Vendors the page builder (AlUmmahNow `packages/shared-types/src/page-blocks*`; wiki
 * AUN-CMS-PAGE-BUILDER) at a pinned commit, and records each source's sha256 in
 * `page-blocks.lock.json`. AlUmmahNowUI vendors the same files, so the CMS editor, its live preview,
 * the public API, www, the scholar sites and the videos site share one schema and one renderer.
 *
 *   node --experimental-strip-types scripts/sync-page-blocks.ts --ref <sha>   (fetch, write, lock)
 *   node --experimental-strip-types scripts/sync-page-blocks.ts --check       (offline: files == lock)
 *
 * The monorepo is public: files come from raw.githubusercontent.com with no token. The CSS is
 * wrapped in a TypeScript string (the Worker serves admin assets from strings).
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const REPO = "Al-Ummah-Now/AlUmmahNow";
const DIR = "packages/shared-types/src";
const LOCK = "page-blocks.lock.json";
const FILES: { src: string; out: string; css?: boolean }[] = [
   { src: "page-blocks.ts", out: "src/lib/page-blocks.generated.ts" },
   { src: "page-blocks.sample.ts", out: "src/lib/page-blocks.sample.generated.ts" },
   { src: "page-blocks.css", out: "src/admin/theme/page-blocks-css.generated.ts", css: true },
];

interface Lock {
   repo: string;
   ref: string;
   files: Record<string, string>;
}

const sha256 = (s: string) => createHash("sha256").update(s).digest("hex");
const header = (ref: string, src: string) => `// Generated by scripts/sync-page-blocks.ts from ${REPO}@${ref}:${DIR}/${src}. Do not edit.\n`;

/** Vendored file → the source text it was made from. */
export function sourceOf(vendored: string, css: boolean): string {
   const nl = vendored.indexOf("\n");
   const body = vendored.startsWith("// Generated by scripts/sync-page-blocks.ts") && nl >= 0 ? vendored.slice(nl + 1) : vendored;
   if (!css) return body;
   const m = body.match(/^export const PAGE_BLOCKS_CSS = (".*");\n$/s);
   return m ? (JSON.parse(m[1]) as string) : body;
}

function wrap(ref: string, f: (typeof FILES)[number], text: string): string {
   return header(ref, f.src) + (f.css ? `export const PAGE_BLOCKS_CSS = ${JSON.stringify(text)};\n` : text);
}

function check(): void {
   const lock = JSON.parse(readFileSync(LOCK, "utf8")) as Lock;
   for (const f of FILES) {
      const file = readFileSync(f.out, "utf8");
      if (!file.startsWith(header(lock.ref, f.src))) throw new Error(`${f.out}: header does not name ${lock.ref}; run npm run sync:page-blocks -- --ref ${lock.ref}`);
      const got = sha256(sourceOf(file, !!f.css));
      if (got !== lock.files[f.src]) throw new Error(`${f.out} differs from ${REPO}@${lock.ref}:${DIR}/${f.src} (sha256 ${got} ≠ ${lock.files[f.src]}). Never edit it by hand: change the monorepo, then npm run sync:page-blocks -- --ref <sha>.`);
   }
   console.log(`check:page-blocks: OK (${REPO}@${lock.ref.slice(0, 12)})`);
}

async function sync(ref: string): Promise<void> {
   if (!/^[0-9a-f]{40}$/.test(ref)) throw new Error("--ref must be a full commit sha");
   const lock: Lock = { repo: REPO, ref, files: {} };
   for (const f of FILES) {
      const url = `https://raw.githubusercontent.com/${REPO}/${ref}/${DIR}/${f.src}`;
      const res = await fetch(url);
      if (!res.ok) throw new Error(`${url}: ${res.status}`);
      const text = await res.text();
      if (!f.css && /^\s*import\s/m.test(text)) throw new Error(`${f.src} must stay self-contained (no imports)`);
      writeFileSync(f.out, wrap(ref, f, text));
      lock.files[f.src] = sha256(text);
   }
   writeFileSync(LOCK, `${JSON.stringify(lock, null, 2)}\n`);
   console.log(`sync:page-blocks: ${FILES.length} files ← ${REPO}@${ref.slice(0, 12)}`);
}

const args = process.argv.slice(2);
if (args.includes("--check")) check();
else {
   const i = args.indexOf("--ref");
   await sync(i >= 0 ? (args[i + 1] ?? "") : "");
}
