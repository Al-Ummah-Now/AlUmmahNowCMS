/**
 * Bundles src/admin/client/main.ts (browser ES2022, minified) into src/admin/client.generated.ts.
 *   node --experimental-strip-types scripts/build-admin-client.ts          write
 *   node --experimental-strip-types scripts/build-admin-client.ts --check  CI: fail if stale
 */
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";

const OUT = "src/admin/client.generated.ts";
const result = await build({
   entryPoints: ["src/admin/client/main.ts"],
   bundle: true,
   format: "esm",
   target: "es2022",
   minify: true,
   write: false,
   legalComments: "none",
   charset: "utf8",
});
const js = result.outputFiles[0].text;
const body = `// Generated by scripts/build-admin-client.ts from src/admin/client/*.ts. Do not edit.\nexport const CLIENT_JS = ${JSON.stringify(js)};\n`;
if (process.argv.includes("--check")) {
   let current = "";
   try {
      current = readFileSync(OUT, "utf8");
   } catch {
      /* missing */
   }
   if (current !== body) {
      console.error(`${OUT} is stale. Run: npm run build:client`);
      process.exit(1);
   }
   console.log(`${OUT} is current (${js.length} bytes)`);
} else {
   writeFileSync(OUT, body);
   console.log(`wrote ${OUT} (${js.length} bytes)`);
}
